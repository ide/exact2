const MAP = new Map(NAMES);

/** The Material glyph an SF name draws, or undefined. */
export function material(name) {
  if (MAP.has(name)) return MAP.get(name);
  const i = name.indexOf('.fill');
  if (i < 0) return undefined;
  const base = MAP.get(name.slice(0, i) + name.slice(i + 5));
  return base && !base.endsWith('-fill') ? base + '-fill' : base;
}

// A glyph's path is one `<path>` of M/L/H/V/Q/T/Z commands in a `0 -960 960 960`
// box; its tight bounds (quadratic extremes included) size the image as SF's
// do (sf-symbols.js).
function bounds(d) {
  let x = 0, y = 0, sx = 0, sy = 0, cx = 0, cy = 0, prev = '';
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  const add = (px, py) => { x0 = Math.min(x0, px); y0 = Math.min(y0, py); x1 = Math.max(x1, px); y1 = Math.max(y1, py); };
  const quad = (qx, qy, ex, ey) => {
    const tx = (x - qx) / (x - 2 * qx + ex), ty = (y - qy) / (y - 2 * qy + ey);
    for (const t of [tx, ty]) if (t > 0 && t < 1) add((1 - t) ** 2 * x + 2 * (1 - t) * t * qx + t * t * ex, (1 - t) ** 2 * y + 2 * (1 - t) * t * qy + t * t * ey);
    add(ex, ey); cx = qx; cy = qy; x = ex; y = ey;
  };
  for (const [, op, args] of d.matchAll(/([MLHVQTZmlhvqtz])([^MLHVQTZmlhvqtz]*)/g)) {
    const n = (args.match(/-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/gi) ?? []).map(Number), rel = op === op.toLowerCase(), o = op.toUpperCase();
    const step = { M: 2, L: 2, H: 1, V: 1, Q: 4, T: 2, Z: 0 }[o];
    if (o === 'Z') { x = sx; y = sy; prev = 'Z'; continue; }
    for (let i = 0; i < n.length; i += step) {
      const a = n.slice(i, i + step), bx = rel ? x : 0, by = rel ? y : 0;
      const k = o === 'M' && i > 0 ? 'L' : o;
      if (k === 'M') { x = bx + a[0]; y = by + a[1]; sx = x; sy = y; add(x, y); }
      else if (k === 'L') { x = bx + a[0]; y = by + a[1]; add(x, y); }
      else if (k === 'H') { x = bx + a[0]; add(x, y); }
      else if (k === 'V') { y = by + a[0]; add(x, y); }
      else if (k === 'Q') quad(bx + a[0], by + a[1], bx + a[2], by + a[3]);
      else quad(/[QT]/.test(prev) ? 2 * x - cx : x, /[QT]/.test(prev) ? 2 * y - cy : y, bx + a[0], by + a[1]);
      prev = k;
    }
  }
  return [x0, y0, x1 - x0, y1 - y0].map(v => Math.round(v * 10) / 10);
}

/** `sf.js`: every SF name among `strings` (each also tried without a
 * `symbol:sf/` prefix) — every mapped name when `strings` is null — with
 * its glyph, registered with sf-symbols.js and re-exporting it. */
export function sfModule(strings) {
  const names = strings ? [...new Set([...strings].map(s => s.startsWith('symbol:sf/') ? s.slice(10) : s))].filter(material) : [...new Set(NAMES.map(([sf]) => sf))];
  if (names.length && !existsSync(glyphs)) throw new Error(`SF Symbols' web glyphs are missing (${glyphs}): run \`bun install --frozen-lockfile\` in exact2`);
  const paths = new Map(), entries = [];
  for (const name of names.sort()) {
    const m = material(name);
    if (!paths.has(m)) {
      const d = readFileSync(resolve(glyphs, m + '.svg'), 'utf8').match(/ d="([^"]+)"/)[1];
      paths.set(m, [paths.size, d, bounds(d)]);
    }
    entries.push(`${JSON.stringify(name)}:${paths.get(m)[0]}`);
  }
  const glyphList = [...paths.values()].map(([, d, b]) => `[${JSON.stringify(d)},${b.join(',')}]`);
  // The wasm host's glue loads it as a script and reads it from `exact.sfSymbols` (its loadAfterPaint).
  const global = strings ? '' : "import * as sf from './sf-symbols.js';\n(globalThis.exact ??= {}).sfSymbols = sf;\n";
  return `import { sfGlyphs } from './sf-symbols.js';\nexport * from './sf-symbols.js';\n${global}const G=[${glyphList.join(',\n')}];\nsfGlyphs({${entries.map(e => e.replace(/:(\d+)$/, ':G[$1]')).join(',')}});\n`;
}
